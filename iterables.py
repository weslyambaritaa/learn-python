# Iterables = An object/collesction that can returns
#             its elements one at a time allowing it to be
#             iterated over in a loop.

numbers = [1, 2, 3, 4, 5]

for number in numbers :
    print(number )

my_dictionaries = {"A" : 1,
                   "B" : 2,
                   "C" : 3}

for key, value in my_dictionaries.items():
    print(key, value)